def test_hash_continuations_comments_and_markers_are_parsed(tmp_path):
    root = tmp_path / "repo"
    root.mkdir()
    write(
        root,
        "environments/requirements.lock",
        "# This file was autogenerated by uv\n"
        "#    uv pip compile x.in --output-file y {}\n".format(BACKSLASH)
        + "#      --generate-hashes\n"
        + "absl-py==2.5.0 {}\n".format(BACKSLASH)
        + "    --hash=sha256:{} {}\n".format("0" * 64, BACKSLASH)
        + "    --hash=sha256:{}\n".format("1" * 64)
        + "    # via keras\n"
        + '\nnvidia-nccl-cu12==2.30.7 ; platform_system == "Linux"\n'
        + "cachecontrol[filecache]==0.14.4\n",
    )
    write(root, "requirements.txt", "absl-py==2.5.0\nnvidia_nccl_cu12==2.30.7\ncachecontrol==0.14.4\n")
    code, report = run_gate(root)
    assert code == gate.EXIT_OK
    assert report["locked_distribution_count"] == 3


def test_comment_ending_in_backslash_does_not_continue(tmp_path):
    """The CI render manifest header has exactly this shape.

    If a comment were allowed to continue, the following comment line would be
    swallowed and a documentation line could be read as a requirement.
    """
    text = (
        "#   pip download nbclient==1 ipykernel==2 -d /tmp/pkgs {}\n".format(BACKSLASH)
        + "#     --python-version 3.13 --only-binary :all: {}\n".format(BACKSLASH)
        + "#     --platform manylinux_2_17_x86_64\n"
        + "asttokens==3.0.2\n"
    )
    lines = gate.logical_lines(text)
    assert lines == [(4, "asttokens==3.0.2")]


def test_multiple_hash_continuation_lines_collapse_to_one_requirement():
    """Four physical lines (pin, two hashes, a trailing 'via' comment) -> one logical line."""
    text = pinned("aiohttp", "3.14.3", hashed=True)
    lines = gate.logical_lines(text)
    assert len(lines) == 1, lines
    assert lines[0][0] == 1
    assert lines[0][1].startswith("aiohttp==3.14.3")
    req = gate.parse_requirement_line("f", lines[0][0], lines[0][1])
    assert req is not None and req.normalized == "aiohttp"


