def test_live_repo_lock_is_fully_covered():
    """The invariant this gate enforces, asserted against the real checkout."""
    if not (REPO_ROOT / gate.DEFAULT_LOCK).is_file():
        pytest.skip("lock file absent from this checkout")
    code, report = gate.run(REPO_ROOT, gate.DEFAULT_LOCK, False)
    assert report["uncovered"] == [], gate.render(report, code)
    assert code == gate.EXIT_OK
    assert report["locked_distribution_count"] > 100
    assert report["covered_count"] == report["locked_distribution_count"]


def test_live_repo_discovery_reproduces_the_measured_manifest_set():
    """The hardcoded filename rule must still reproduce the calibration.

    Measured against the live dependency graph on the date recorded in the
    tool. If this list drifts, re-run the calibration query in the tool's
    header before changing either side.
    """
    if not (REPO_ROOT / gate.DEFAULT_LOCK).is_file():
        pytest.skip("not the SESTRAV checkout")
    measured = {
        "pyproject.toml",
        "requirements.txt",
        "environments/requirements-ci-build.txt",
        "environments/requirements-ci-mypy.txt",
        "environments/requirements-ci-pytest-cov.txt",
        "environments/requirements-ci-render.txt",
        "environments/requirements-ci-ruff.txt",
        "environments/requirements-ci-torch-cpu.txt",
        "environments/requirements-ci.txt",
        "environments/requirements-pip-audit.txt",
        "environments/requirements-pip-bootstrap.txt",
        "environments/requirements-sbom.txt",
        "environments/requirements-security.txt",
        "environments/requirements-semgrep.txt",
        "environments/requirements-lock.in",
    }
    derived = set(gate.discover_parsed_manifests(REPO_ROOT))
    assert derived == measured, "derived-only={} measured-only={}".format(
        sorted(derived - measured), sorted(measured - derived)
    )
