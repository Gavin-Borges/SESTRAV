"""Tests for the lockfile / parsed-manifest coverage gate.

No network. Every fixture is a synthetic repository under ``tmp_path``.

The gate exists because ``environments/requirements.lock`` is installed from but
is not parsed by GitHub's dependency graph, so anything pinned only there is
permanently invisible to Dependabot. These tests are the load-bearing half: if
they cannot fail, the gate is decoration.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
MODULE_PATH = REPO_ROOT / "tools" / "check_lock_manifest_coverage.py"

_spec = importlib.util.spec_from_file_location("check_lock_manifest_coverage", MODULE_PATH)
assert _spec is not None and _spec.loader is not None
gate = importlib.util.module_from_spec(_spec)
sys.modules["check_lock_manifest_coverage"] = gate
_spec.loader.exec_module(gate)

BACKSLASH = chr(92)


# ---------------------------------------------------------------------------
# Fixture helpers
# ---------------------------------------------------------------------------


def write(root: Path, rel: str, text: str) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def pinned(name: str, version: str = "1.0.0", hashed: bool = False) -> str:
    """One requirement, optionally in the hashed continuation shape uv emits."""
    if not hashed:
        return "{}=={}\n".format(name, version)
    return (
        "{}=={} {}\n".format(name, version, BACKSLASH)
        + "    --hash=sha256:{} {}\n".format("a" * 64, BACKSLASH)
        + "    --hash=sha256:{}\n".format("b" * 64)
        + "    # via something\n"
    )


def make_repo(tmp_path: Path, lock_names, manifest_names, hashed: bool = True) -> Path:
    """A synthetic repo: one unparsed lock plus one parsed requirements manifest."""
    root = tmp_path / "repo"
    root.mkdir(exist_ok=True)
    write(
        root,
        "environments/requirements.lock",
        "# autogenerated\n" + "".join(pinned(n, hashed=hashed) for n in lock_names),
    )
    write(
        root,
        "requirements.txt",
        "# parsed by GitHub\n" + "".join(pinned(n, hashed=hashed) for n in manifest_names),
    )
    return root


def run_gate(root: Path, **kwargs):
    return gate.run(root, kwargs.pop("lock", "environments/requirements.lock"), kwargs.pop("follow_includes", False))


