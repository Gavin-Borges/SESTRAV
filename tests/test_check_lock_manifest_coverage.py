def test_a_second_requirement_on_one_line_is_never_silently_dropped(tmp_path):
    """End to end: the half-read line must stop the gate, not shrink its scope."""
    root = make_repo(tmp_path, lock_names=["alpha"], manifest_names=["alpha"], hashed=False)
