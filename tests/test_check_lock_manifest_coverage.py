def test_parsed_manifest_rule_matches_txt_and_pyproject():
    files = frozenset({"pyproject.toml", "requirements.txt", "environments/requirements-ci.txt"})
    assert gate.is_parsed_manifest("pyproject.toml", files)
    assert gate.is_parsed_manifest("requirements.txt", files)
    assert gate.is_parsed_manifest("environments/requirements-ci.txt", files)


