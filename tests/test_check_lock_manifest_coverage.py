def test_normalization_equivalence_passes_end_to_end(tmp_path):
    """Flask_Login in the lock against flask-login in a manifest must PASS.

    Getting normalization wrong here manufactures a false failure, which is the
    fastest way to get a gate switched off.
    """
    root = make_repo(tmp_path, lock_names=["Flask_Login", "flask.login-Extra"], manifest_names=["flask-login", "FLASK_LOGIN.EXTRA"])
    code, report = run_gate(root)
    assert report["uncovered"] == []
    assert code == gate.EXIT_OK


def test_normalization_does_not_collapse_distinct_projects(tmp_path):
    """A collapse that is too aggressive would hide a real gap."""
    root = make_repo(tmp_path, lock_names=["flask-login2"], manifest_names=["flask-login"])
    code, report = run_gate(root)
    assert code == gate.EXIT_FINDINGS
    assert [item["normalized"] for item in report["uncovered"]] == ["flask-login2"]


