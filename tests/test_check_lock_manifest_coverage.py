    assert finding["normalized"] == "orphan-pkg"
    assert finding["lock_line"] > 0
    assert "orphan-pkg" in finding["lock_text"]

    text = gate.render(report, code)
    assert "orphan-pkg" in text
    assert "Dependabot cannot see" in text
    assert "environments/requirements.lock line {}".format(finding["lock_line"]) in text


