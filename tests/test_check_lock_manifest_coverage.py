def test_lock_only_package_fails_and_is_named(tmp_path):
    root = make_repo(tmp_path, lock_names=["alpha", "orphan-pkg", "beta"], manifest_names=["alpha", "beta"])
    code, report = run_gate(root)
    assert code == gate.EXIT_FINDINGS
