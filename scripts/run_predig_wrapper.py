"""
SESTRAV PredIG Snakemake Rule Wrapper.
Builds recombinant inputs, runs PredIG via Docker if available, else generates simulated scores.
"""

import os
import re
import sys
import argparse
import subprocess
from pathlib import Path

import pandas as pd
import numpy as np

# The run_predig rule runs this file by path, which puts scripts/ rather than the
# repository root first on sys.path. Without this, the deferred `src` import in
# main() fails wherever the package is not installed, and resolves to whatever
# `src` the environment has installed, not this tree's, wherever one is.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


# Stage 2 writes its per-allele presentation scores as WIDE columns, named by
# functions/stage2_mhc_binding_prediction.py's `_allele_to_col`. That one-line rule is
# COPIED here rather than imported: that module imports mhcflurry at module level
# (measured 2026-10-18 in the sestrav env: 3.9 s and over 2,300 modules, torch among
# them), a heavy import for a one-line string rule.
# tests/test_predig_simulation_reads_stage2_binding_columns.py pins the two as agreeing.
def _stage2_binding_column(allele):
    """Return stage 2's wide column name for an allele: 'HLA-A*02:01' -> 'bind_A0201'."""
    return "bind_" + re.sub(r"[^A-Za-z0-9]", "", allele.replace("HLA-", ""))


def main():
    parser = argparse.ArgumentParser(description="Run PredIG or mock it if missing")
    parser.add_argument("--binding-csv", required=True, help="Input MHC binding stage CSV")
    parser.add_argument("--output", required=True, help="Output PredIG raw CSV file")
    parser.add_argument("--alleles", required=True, help="Comma-separated alleles list")
    # Optional, so existing invocations keep working. Stage 2's binding CSV carries no
    # proteome_id column, so without this the recombinant input cannot be built at all
    # and this wrapper simulates; see the note above the fallback below.
    parser.add_argument(
        "--proteome-id",
        default=None,
        help="Proteome id for the binding CSV (rule run_predig passes its wildcard)",
    )
    # Optional too. The FASTA the binding CSV's peptides were cut from, so PredIG gets
    # their real parent protein. Without it only the two panels PROTEOME_FASTA names
    # find one, and every other antigen's peptides get synthetic glycine context.
    parser.add_argument(
        "--proteome-fasta",
        default=None,
        help="FASTA the peptides came from (rule run_predig passes generate_peptides' input)",
    )
    args = parser.parse_args()

    if not os.path.isfile(args.binding_csv):
        print(f"Error: binding file not found: {args.binding_csv}")
        sys.exit(1)

    df = pd.read_csv(args.binding_csv)

    # Check if docker is available
    docker_found = False
    try:
        res = subprocess.run(
            ["docker", "--version"], stdout=subprocess.PIPE, stderr=subprocess.PIPE
        )
        if res.returncode == 0:
            docker_found = True
    # Only a real "docker is not usable here" signal: a missing binary is
    # FileNotFoundError (an OSError), and subprocess's own failures are
    # SubprocessError, which is NOT an OSError, so both members are needed.
    # A bare `except:` here also swallowed KeyboardInterrupt, so a Ctrl-C
    # during tool detection silently became docker_found=False and produced
    # a simulated artifact.
    except (OSError, subprocess.SubprocessError):
        pass

    # Build recombinant input path
    # We place the inputs and outputs in results/ to match mounts
    repo_root = os.path.abspath(".")
    results_dir = os.path.join(repo_root, "results")
    os.makedirs(results_dir, exist_ok=True)

    # We generate a temporary recombinant CSV for PredIG
    temp_predig_input_rel = "results/temp_predig_input.csv"
    temp_predig_input_abs = os.path.join(repo_root, temp_predig_input_rel)

    # We need a pairs csv first
    # In Stage 2 output binding CSV, columns are: peptide, HLA-A*02:01, HLA-A*01:01, etc.
    # or the rows represent peptide-allele bindings.
    # Let's check the columns in our binding CSV.
    # In iedb_data_loader: binding files are generated by Stage 2.
    # Let's construct a list of peptide-allele pairs
    alleles_list = args.alleles.split(",")
    pairs = []

    # Identify HLA columns or use the alleles list
    hla_cols = [c for c in df.columns if c in alleles_list or c.startswith("HLA-")]
    if not hla_cols:
        hla_cols = alleles_list

    peptides = df["peptide"].unique()
    for pep in peptides:
        for allele in hla_cols:
            pairs.append({"peptide": pep, "allele": allele})

    pairs_df = pd.DataFrame(pairs)
    temp_pairs_path = os.path.join(results_dir, "temp_predig_pairs.csv")
    pairs_df.to_csv(temp_pairs_path, index=False)

    # Now run build_predig_recombinant_input.py
    # We import and call build_recombinant_table directly to avoid subprocess overhead
    try:
        from src.build_predig_recombinant_input import build_recombinant_table

        proteome_dir = os.path.join(repo_root, "data", "proteomes")
        build_recombinant_table(
            pairs_path=temp_pairs_path,
            validation_input_path=args.binding_csv,
            proteome_dir=proteome_dir,
            output_path=temp_predig_input_abs,
            proteome_id=args.proteome_id,
            proteome_fasta=args.proteome_fasta,
        )
        predig_input_built = True
    # build_recombinant_table does file I/O (OSError) and DataFrame column
    # work (KeyError, ValueError). Anything else is a defect in this wrapper
    # and must not be reported as "failed to build recombinant input".
    except (OSError, ValueError, KeyError) as e:
        print(f"[PredIG Wrapper] Failed to build recombinant input: {e}")
        predig_input_built = False

    # Try executing Docker
    if docker_found and predig_input_built:
        # We need relative filenames for docker mount
        input_rel_docker = f"/predig/{os.path.basename(temp_predig_input_abs)}"
        output_rel_docker = f"/predig/{os.path.basename(args.output)}"

        cmd = [
            "docker",
            "run",
            "--rm",
            "-v",
            f"{results_dir}:/predig",
            # Pinned off :latest for supply-chain reproducibility (2026-08-08 security sweep,
            # W14.4). Same digest already validated and pinned in run_predig_batched.py /
            # run_external_tier_a.ps1 / run_external_tier_b.ps1 - reused here for consistency
            # rather than pinning a second, untested digest for the same image.
            "bsceapm/predig@sha256:4a0c8b6b23a968600c4363290dc778a4b6e51cc24032d16ebfdb3119846b0a79",
            input_rel_docker,
            "--output",
            output_rel_docker,
            "--model",
            "path",
            "--type",
            "recombinant",
        ]

        # Defensive: do not allow mounting root-adjacent paths
        output_dir = os.path.dirname(os.path.abspath(args.output))
        sensitive_roots = {"/", "/etc", "/usr", "/bin", "/sbin", "/lib", "/proc", "/sys"}
        if output_dir in sensitive_roots or not output_dir:
            sys.exit(f"Error: output path resolves to a sensitive location: {output_dir!r}")

        try:
            print(f"[PredIG Wrapper] Running Docker: {' '.join(cmd)}")
            # Docker volume mount scoped to dirname(args.output); researcher-only CLI, no web
            # exposure. cmd is a LIST and shell=False, so no shell interpretation occurs and the
            # rule's command-injection premise does not apply.
            # The bare inline `# nosemgrep` below is deliberate and must not be "tidied" into a
            # rule-qualified or preceding-line form. The version used here until 2026-08-16 was
            # inert for TWO independent reasons, so this finding surfaced on every scan while
            # looking suppressed: (1) it sat on a preceding line with another comment between it
            # and the statement, and semgrep only honours the finding's own line or the one
            # immediately before it; (2) it named the rule as
            # `python.lang.security.audit.dangerous-subprocess-use-tainted-env-args`, which is the
            # rule PATH - the real id repeats the final component, so the qualified form never
            # matched. run_predig_batched.py already uses this bare inline form for the same rule
            # and reports clean; that is the control this was verified against.
            subprocess.run(cmd, check=True)  # nosemgrep
            print("[PredIG Wrapper] Execution completed successfully.")

            # Clean up temp files
            for p in [temp_pairs_path, temp_predig_input_abs]:
                if os.path.isfile(p):
                    os.remove(p)
            sys.exit(0)
        # Narrow so that only an actual docker/subprocess failure falls back to
        # simulation. sys.exit(0) above raises SystemExit, which is a
        # BaseException and was never caught here; that is preserved.
        except (OSError, subprocess.SubprocessError) as e:
            print(
                f"[PredIG Wrapper] Docker failed: {e}. Falling back to simulation.", file=sys.stderr
            )

    # Cleanup temp pairs
    if os.path.isfile(temp_pairs_path):
        os.remove(temp_pairs_path)

    # Fallback to simulation. The scores below are seeded noise, not PredIG output,
    # and this script still exits 0, so the Snakemake default target is satisfied
    # either way. Every simulated row therefore carries simulated=1, which
    # scripts/standardize_outputs.py turns into predig_simulated in the standardized
    # CSV; real PredIG output has no such column.
    #
    # Both defects this comment used to carry are now FIXED, so a simulated score is
    # binding-derived wherever the input supplies a binding value for the allele.
    #
    # (1) build_recombinant_table selected peptide, proteome_id and virus, and
    # functions/stage2_mhc_binding_prediction.py writes none of the last two, so it
    # raised KeyError and predig_input_built was always False. The proteome id now
    # arrives by --proteome-id, which rule run_predig passes from its wildcard. Called
    # without that flag on a stage-2 CSV the build still fails, ValueError now rather
    # than KeyError, and this branch is still reached.
    #
    # (2) bind_map matched a column only if it was named HLA-... or exactly like an
    # allele, while stage 2 writes wide bind_A0201-style columns, so bind_map stayed
    # empty, every bind_val below kept its 0.5 default, and the simulated score was
    # noise around the constant 0.375 carrying no binding signal at all. Each requested
    # allele is now resolved to stage 2's column name as well (to-do PC-PG2). bind_val
    # still falls back to 0.5 where neither spelling of the column is present, so an
    # allele the input has no binding values for is still noise around a constant.
    #
    # What is NOT fixed, because it is not a defect: these rows are still SIMULATED and
    # still carry simulated=1. Binding-derived noise is not PredIG output.
    print(
        "[PredIG Wrapper] WARNING: Docker is unavailable or the PredIG input could not "
        "be built. Writing SIMULATED scores (seeded noise around each row's binding "
        "value where the input has one for the allele, else around a constant), not "
        "PredIG output.",
        file=sys.stderr,
    )
    np.random.seed(42)

    # Extract binding mappings for correlation, keyed by the ALLELE name because the
    # loop below looks them up by allele rather than by column. Two column spellings
    # are accepted, in this order: a column named exactly like the allele (the
    # HLA-A*02:01-style wide frame some callers pass), then stage 2's bind_A0201-style
    # column, which is what the CSV `rule run_predig` passes actually carries.
    # Blank cells are DROPPED rather than mapped: min(1.0, nan) returns 1.0, so an
    # absent presentation score would otherwise score that row as the strongest
    # possible binder instead of falling through to the 0.5 default below.
    bind_map = {}
    for allele in alleles_list:
        for col in (allele, _stage2_binding_column(allele)):
            if col in df.columns:
                bind_map[allele] = df.set_index("peptide")[col].dropna().to_dict()
                break

    mock_rows = []
    # Write standard columns: peptide, allele, predig_score, simulated
    for pep in peptides:
        for allele in alleles_list:
            # check if we can get a real binding value
            bind_val = 0.5
            if allele in bind_map and pep in bind_map[allele]:
                bind_val = bind_map[allele][pep]
                # If it's raw IC50 affinity, convert to score [0, 1]
                if bind_val > 1.0:
                    bind_val = 1.0 - min(bind_val, 5000) / 5000

            predig_score = max(0.0, min(1.0, bind_val * 0.75 + np.random.normal(0, 0.12)))
            mock_rows.append(
                {"peptide": pep, "allele": allele, "predig_score": predig_score, "simulated": 1}
            )

    mock_df = pd.DataFrame(mock_rows)
    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    mock_df.to_csv(args.output, index=False)
    print(f"[PredIG Wrapper] Saved simulated PredIG output ({len(mock_df)} rows) to {args.output}")

    # Cleanup temp input if it exists
    if os.path.isfile(temp_predig_input_abs):
        os.remove(temp_predig_input_abs)


if __name__ == "__main__":
    main()
